// One-off generator: turns scripts/reading-content.ts into
// src/db/migrations/0006_reading_topics.sql. Run with:
//   npx tsx scripts/gen-reading-topics-migration.mjs
// Re-run any time reading-content.ts changes and the migration needs
// regenerating (only meaningful before 0006 has actually been applied
// anywhere, since migrations are one-shot by filename).
import { writeFileSync } from "node:fs";
import path from "node:path";
import { newReadingBank, existingTopicByTitle } from "./reading-content.ts";

function sqlString(s) {
  return `'${s.replace(/'/g, "''")}'`;
}
function sqlJsonb(value) {
  return `${sqlString(JSON.stringify(value))}::jsonb`;
}

const statements = [];

statements.push(`ALTER TABLE "reading_passages" ADD COLUMN "topic" text;`);

for (const [title, topic] of Object.entries(existingTopicByTitle)) {
  statements.push(`UPDATE "reading_passages" SET "topic" = ${sqlString(topic)} WHERE "title" = ${sqlString(title)} AND "parent_id" IS NULL;`);
}

const valuesRows = newReadingBank.map((p) => {
  return `(NULL, ${p.grade}, ${sqlString(p.title)}, ${sqlString(p.kind)}, ${sqlString(p.topic)}, ${sqlString(p.body)}, ${p.words}, ${sqlJsonb(p.mc)}, ${sqlJsonb(p.writing)})`;
});

statements.push(
  `INSERT INTO "reading_passages" ("parent_id", "grade", "title", "kind", "topic", "body", "words", "mc", "writing") VALUES\n${valuesRows.join(",\n")};`
);

const header = `-- Generated by scripts/gen-reading-topics-migration.mjs from scripts/reading-content.ts.
-- Do not hand-edit; regenerate instead if the content changes.

`;
const out = header + statements.join("\n--> statement-breakpoint\n") + "\n";

const outPath = path.resolve(import.meta.dirname, "../src/db/migrations/0006_reading_topics.sql");
writeFileSync(outPath, out, "utf-8");
console.log(`Wrote ${outPath} (${statements.length} statements, ${newReadingBank.length} new passages).`);
